from __future__ import annotations

import logging

from openai import AsyncOpenAI

from ..config import Settings
from ..events import PullRequestEvent
from ..review.agent import CodeQualityAgent, ReviewComment, ReviewResult
from ..review.diff import commentable_lines, truncate_diff
from ..review.github import GitHubClient
from .base import Handler

log = logging.getLogger("prharness.handlers.code_review")

_SEVERITY_ORDER = {"high": 0, "medium": 1, "low": 2}
HEADER = "## AI code quality review"


class CodeReviewHandler(Handler):
    """Runs the OpenAI code-quality agent on a PR and posts the result as a PR review.

    Read-only apart from that review: it never pushes commits or edits the PR, and the
    review is always a plain ``COMMENT`` (it never approves or requests changes).

    Requires ``OPENAI_API_KEY`` and ``GITHUB_TOKEN`` (with pull request write access).
    """

    name = "code_review"

    def __init__(
        self,
        settings: Settings,
        *,
        github: GitHubClient | None = None,
        openai_client: AsyncOpenAI | None = None,
    ) -> None:
        super().__init__(settings)
        missing = [
            env
            for env, value in (
                ("OPENAI_API_KEY", settings.openai_api_key),
                ("GITHUB_TOKEN", settings.github_token),
            )
            if not value.get_secret_value().strip()
        ]
        if missing and (github is None or openai_client is None):
            raise ValueError(f"code_review handler requires {', '.join(missing)}")
        self._github = github or GitHubClient(
            settings.github_token.get_secret_value(), settings.github_api_url
        )
        self._openai = openai_client or AsyncOpenAI(
            api_key=settings.openai_api_key.get_secret_value(),
            base_url=settings.openai_base_url or None,
            timeout=settings.openai_timeout_seconds,
        )
        self._agent = CodeQualityAgent(
            self._openai,
            settings.openai_model,
            max_turns=settings.review_max_turns,
            max_file_reads=settings.review_max_file_reads,
            max_file_chars=settings.review_max_file_chars,
        )

    async def handle(self, event: PullRequestEvent) -> None:
        repo, number = event.repo_full_name, event.number
        diff = await self._github.get_diff(repo, number)
        if not diff.strip():
            log.info("code_review skipped: empty diff pr=%s#%d", repo, number)
            return
        shown, truncated = truncate_diff(diff, self.settings.review_max_diff_chars)

        async def read_file(path: str) -> str | None:
            return await self._github.get_file(repo, path, event.head_sha)

        result = await self._agent.review(event, shown, read_file, diff_truncated=truncated)
        inline, other = _split_comments(
            result, commentable_lines(diff), self.settings.review_max_comments
        )
        body = _review_body(result, other, self.settings.openai_model)
        comments = [
            {"path": c.path, "line": c.line, "side": "RIGHT", "body": _comment_body(c)}
            for c in inline
        ]
        response = await self._github.create_review(
            repo,
            number,
            commit_id=event.head_sha,
            body=body,
            comments=comments,
        )
        if response.status_code == 422 and comments:
            log.warning("inline comments rejected; posting summary only pr=%s#%d", repo, number)
            response = await self._github.create_review(
                repo,
                number,
                commit_id=event.head_sha,
                body=_review_body(result, inline + other, self.settings.openai_model),
                comments=[],
            )
        response.raise_for_status()
        log.info(
            "code_review posted pr=%s#%d inline=%d other=%d", repo, number, len(inline), len(other)
        )

    async def aclose(self) -> None:
        await self._github.aclose()
        await self._openai.close()


def _split_comments(
    result: ReviewResult, allowed: dict[str, set[int]], limit: int
) -> tuple[list[ReviewComment], list[ReviewComment]]:
    ranked = sorted(result.comments, key=lambda c: _SEVERITY_ORDER.get(c.severity, 3))[:limit]
    inline = [c for c in ranked if c.line in allowed.get(c.path, ())]
    other = [c for c in ranked if c not in inline]
    return inline, other


def _comment_body(comment: ReviewComment) -> str:
    return f"**[{comment.severity}] {comment.category}**\n\n{comment.body}"


def _review_body(result: ReviewResult, extra: list[ReviewComment], model: str) -> str:
    parts = [HEADER, "", result.summary or "No summary provided."]
    if extra:
        parts += ["", "### Additional notes"]
        parts += [f"- `{c.path}:{c.line}` **[{c.severity}] {c.category}**: {c.body}" for c in extra]
    parts += ["", f"<sub>Generated by pr-webhook-harness using `{model}`.</sub>"]
    return "\n".join(parts)
